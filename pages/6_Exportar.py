        df = pd.DataFrame(linhas)
        insight = _por_lang(dash, "insight_por_lang", "insight")
        if insight:
            df_insight = pd.DataFrame([{X["analise"]: insight}])
            return {X["sh_dash"]: df, f"{X['sh_dash']} - {X['analise']}": df_insight}
